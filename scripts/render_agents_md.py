"""Regenerate the README "Agents" section from the agents' metadata: uv run python scripts/render_agents_md.py"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from fcagents.catalog import catalog_markdown  # noqa: E402

START, END = "<!-- AGENTS:START -->", "<!-- AGENTS:END -->"
README = ROOT / "README.md"


def render(text: str) -> str:
    block = f"{START}\n<!-- generated by scripts/render_agents_md.py; do not edit by hand -->\n\n{catalog_markdown()}{END}"
    return re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)


if __name__ == "__main__":
    text = README.read_text()
    if START not in text:
        sys.exit(f"{README} has no {START} marker")
    README.write_text(render(text))
    print(f"updated {README}")
